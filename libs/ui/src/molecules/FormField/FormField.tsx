import { useId } from 'react';
import type { ComponentPropsWithRef, ReactNode } from 'react';
import { FieldError } from '../../atoms/FieldError';
import { Label } from '../../atoms/Label';
import { cx } from '../../internal/cx';

/** Props the control must receive to be wired to its label, hint and error. */
export interface FormFieldControlProps {
  id: string;
  'aria-describedby'?: string;
  'aria-invalid'?: true;
  required?: true;
}

export interface FormFieldProps extends Omit<
  ComponentPropsWithRef<'div'>,
  'children'
> {
  /** Text of the label; it comes from the consumer (D17). */
  label: ReactNode;
  required?: boolean;
  hint?: ReactNode;
  error?: ReactNode;
  /** Announces the error immediately (`role="alert"`), e.g. after a submit. */
  announceError?: boolean;
  /** Render prop: spread the received props on any control (no cloning). */
  children: (control: FormFieldControlProps) => ReactNode;
}

const isPresent = (node: ReactNode) =>
  node !== undefined && node !== null && node !== false && node !== '';

/** Label + control + hint + error, wired with ids generated by `useId`. */
export function FormField({
  label,
  required = false,
  hint,
  error,
  announceError = false,
  className,
  children,
  ref,
  ...rest
}: FormFieldProps) {
  const baseId = useId();
  const controlId = `${baseId}-control`;
  const hintId = `${baseId}-hint`;
  const errorId = `${baseId}-error`;
  const hasHint = isPresent(hint);
  const hasError = isPresent(error);
  const describedBy = [hasHint ? hintId : null, hasError ? errorId : null]
    .filter(Boolean)
    .join(' ');

  const control: FormFieldControlProps = {
    id: controlId,
    ...(describedBy ? { 'aria-describedby': describedBy } : {}),
    ...(hasError ? { 'aria-invalid': true as const } : {}),
    ...(required ? { required: true as const } : {}),
  };

  return (
    <div ref={ref} className={cx('flex flex-col gap-1', className)} {...rest}>
      <Label htmlFor={controlId} required={required}>
        {label}
      </Label>
      {children(control)}
      {hasHint ? (
        <p id={hintId} className="font-sans text-sm text-content-muted">
          {hint}
        </p>
      ) : null}
      {hasError ? (
        <FieldError id={errorId} announce={announceError}>
          {error}
        </FieldError>
      ) : null}
    </div>
  );
}
