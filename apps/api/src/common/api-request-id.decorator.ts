import { ApiHeader } from '@nestjs/swagger';
import { REQUEST_ID_PATTERN } from './request-id';

const REQUEST_ID_MAX_LENGTH = 128;

const REQUEST_ID_SCHEMA = {
  type: 'string',
  maxLength: REQUEST_ID_MAX_LENGTH,
  // Same regex the request-id middleware validates with — never restated.
  pattern: REQUEST_ID_PATTERN.source,
} as const;

/**
 * `X-Request-Id` as documented on every response: the middleware sets it on
 * every response, echoing a valid incoming value or a generated UUID.
 * Defined once; pass it as `headers` to `@ApiOkResponse`/`@ApiResponse`.
 */
export const REQUEST_ID_RESPONSE_HEADERS = {
  'X-Request-Id': {
    description:
      'Echoes the valid X-Request-Id sent in the request, or a UUID generated by the API.',
    schema: REQUEST_ID_SCHEMA,
  },
};

/**
 * Optional `X-Request-Id` request header, documented on each operation.
 */
export const ApiRequestIdHeader = (): MethodDecorator =>
  ApiHeader({
    name: 'X-Request-Id',
    required: false,
    description:
      'Optional correlation id. Used as-is when it matches the documented pattern; otherwise the API replaces it with a generated UUID.',
    schema: REQUEST_ID_SCHEMA,
  });
